        primary key,
    description varchar(64)  not null,
    image_url   varchar(64)  not null,
    name        varchar(64)  not null,
    products    varchar(255) not null,
    schedule    varchar(16)  not null,
    market_id   integer
        constraint fkvd9rwtgknfypfx3gufv743qu
            references markets,
    user_id     integer
        constraint uki82lf8yuxfi9idbvdiajm22hr
            unique
        constraint fk4j93irmf4q3omm1helofu12wr
            references users
);

